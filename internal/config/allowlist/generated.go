package allowedext

import (
	"path"
	"regexp"
	"strings"
)

// Generator output that path patterns cannot recognize (zz_generated.deepcopy.go,
// stringer's *_string.go, mockgen, sqlc, ent, gRPC stubs) still announces
// itself in the file header. Only the leading comment block is inspected, so
// a marker quoted in code or in a later comment does not exclude the file.
const (
	generatedHeaderMaxBytes = 8 << 10
	generatedHeaderMaxLines = 64
)

// generatedMarker matches the header conventions of common generators:
//
//	Code generated by X. DO NOT EDIT.                 Go (go/ast.IsGenerated), sqlc, ent, templ
//	Generated by the protocol buffer compiler.  DO NOT EDIT!   protoc, gRPC plugins
//	@generated                                        Meta tooling, Cargo, Relay, protobuf-es
//	<auto-generated>                                  .NET
//
// @generated must stand as a word after the comment prefix or whitespace,
// so a URL or address ending in "/@generated" does not count, and
// <auto-generated> must open the comment text, as .NET writes it, rather than
// be mentioned in prose.
var generatedMarker = regexp.MustCompile(
	`\b(?:Code generated|[Gg]enerated by)\b.*\bDO NOT EDIT\b` +
		`|(?:^(?://+|#+|--|;+|%+)?|[\s*])@generated\b` +
		`|^(?://+|#+|--|;+|%+|\*+)?\s*<auto-generated\b`)

// commentSyntax is how one language writes comments. A prefix that is a
// comment in one language is code in another (";" starts a statement in
// JavaScript, "#" a directive in C), so the header is read with the syntax of
// the file's own language.
type commentSyntax struct {
	line    []string // line-comment prefixes
	notLine []string // code that starts with a line-comment prefix
	block   bool     // /* ... */ comments
	phpTag  bool     // a leading <?php open tag
}

// headerLineBreaks normalizes every line terminator some supported language
// recognizes. JavaScript and C# end a line comment at U+2028, U+2029 and
// U+0085, so text after one is code there. Breaking on them in every language
// only errs towards ending the header early, which keeps the file in review.
var headerLineBreaks = strings.NewReplacer(
	"\r\n", "\n", "\r", "\n", "\u2028", "\n", "\u2029", "\n", "\u0085", "\n")

var commentSyntaxByExt = func() map[string]commentSyntax {
	groups := []struct {
		syntax commentSyntax
		exts   string
	}{
		{commentSyntax{line: []string{"//"}, block: true},
			".java .kt .kts .scala .groovy .gradle .js .jsx .ts .tsx .mjs .cjs " +
				".c .h .cpp .cc .cxx .hpp .hxx .cs .fs .fsi .fsx .go .rs .swift .m .mm " +
				".dart .proto .prisma .json5 .jsonc .sol .v .sv .vh .glsl .hlsl .wgsl " +
				".metal .ets .scss .sass .less .bicep .zig"},
		{commentSyntax{block: true}, ".css"},
		{commentSyntax{line: []string{"//", "#"}, block: true},
			".tf .tofu .hcl .tfvars .thrift .jsonnet .libsonnet"},
		// "#[" opens a PHP 8 attribute, not a comment.
		{commentSyntax{line: []string{"//", "#"}, notLine: []string{"#["}, block: true, phpTag: true}, ".php .phtml"},
		{commentSyntax{line: []string{"#"}},
			".py .pyi .rb .rake .gemspec .sh .bash .zsh .fish .ps1 .psm1 .psd1 " +
				".yaml .yml .toml .r .pl .pm .ex .exs .nim .nims .nimble .nu .graphql .gql " +
				".bzl .bazel .star .cmake .properties .po .pot .rego .jl .capnp .vy"},
		{commentSyntax{line: []string{"#"}, block: true}, ".nix"},
		{commentSyntax{line: []string{"--"}}, ".lua .hs .elm .vhd .vhdl"},
		{commentSyntax{line: []string{"--"}, block: true}, ".sql"},
		{commentSyntax{line: []string{";"}}, ".clj .cljs .cljc .edn"},
		{commentSyntax{line: []string{";", "#"}}, ".ini"},
		{commentSyntax{line: []string{"%"}}, ".erl .hrl"},
	}
	m := make(map[string]commentSyntax)
	for _, g := range groups {
		for _, ext := range strings.Fields(g.exts) {
			m[ext] = g.syntax
		}
	}
	return m
}()

// IsGeneratedFile reports whether content, the file at filePath, opens with a
// comment block that carries a generated-code marker. Comments are read with
// the syntax of the file's language; a language without a known syntax is
// never treated as generated. Only comment text is matched, and scanning
// stops at the first code, even code that follows a comment on the same line,
// or at the header size limits.
func IsGeneratedFile(filePath, content string) bool {
	syntax, ok := commentSyntaxByExt[strings.ToLower(path.Ext(filePath))]
	if !ok || content == "" {
		return false
	}
	if len(content) > generatedHeaderMaxBytes {
		content = content[:generatedHeaderMaxBytes]
	}
	content = headerLineBreaks.Replace(strings.TrimPrefix(content, "\ufeff"))

	inBlock := false
	for i, line := range strings.SplitN(content, "\n", generatedHeaderMaxLines+1) {
		if i == generatedHeaderMaxLines {
			break
		}
		found, done := syntax.scanHeaderLine(strings.TrimSpace(line), &inBlock)
		if found {
			return true
		}
		if done {
			return false
		}
	}
	return false
}

// scanHeaderLine walks the comments on one header line. found reports a
// marker inside comment text; done reports that the line reached code, which
// ends the header. inBlock carries an open /* */ comment across lines.
func (s commentSyntax) scanHeaderLine(line string, inBlock *bool) (found, done bool) {
	for line != "" {
		if *inBlock {
			end := strings.Index(line, "*/")
			if end < 0 {
				return generatedMarker.MatchString(line), false
			}
			if generatedMarker.MatchString(line[:end]) {
				return true, false
			}
			*inBlock = false
			line = strings.TrimSpace(line[end+2:])
			continue
		}
		switch {
		case s.block && strings.HasPrefix(line, "/*"):
			*inBlock = true
			line = line[2:]
		case s.phpTag && strings.HasPrefix(line, "<?php"):
			line = strings.TrimSpace(line[len("<?php"):])
		case s.isLineComment(line):
			return generatedMarker.MatchString(line), false
		default:
			return false, true
		}
	}
	return false, false
}

func (s commentSyntax) isLineComment(line string) bool {
	for _, p := range s.notLine {
		if strings.HasPrefix(line, p) {
			return false
		}
	}
	for _, p := range s.line {
		if strings.HasPrefix(line, p) {
			return true
		}
	}
	return false
}

package allowedext

import (
	"regexp"
	"strings"
)

// Generator output that path patterns cannot recognize (zz_generated.deepcopy.go,
// stringer's *_string.go, mockgen, sqlc, ent, gRPC stubs) still announces
// itself in the file header. Only the leading comment block is inspected, so
// a marker quoted in code or in a later comment does not exclude the file.
const (
	generatedHeaderMaxBytes = 8 << 10
	generatedHeaderMaxLines = 64
)

// generatedMarker matches the header conventions of common generators:
//
//	Code generated by X. DO NOT EDIT.                 Go (go/ast.IsGenerated), sqlc, ent, templ
//	Generated by the protocol buffer compiler.  DO NOT EDIT!   protoc, gRPC plugins
//	@generated                                        Meta tooling, Cargo, Relay, protobuf-es
//	<auto-generated>                                  .NET
var generatedMarker = regexp.MustCompile(
	`\b(?:Code generated|[Gg]enerated by)\b.*\bDO NOT EDIT\b` +
		`|(?:^|[^\w@-])@generated\b` +
		`|<auto-generated\b`)

// IsGeneratedContent reports whether the leading comment block of content
// carries a generated-code marker. Only comment text is matched, and scanning
// stops at the first code, even when it follows a comment on the same line,
// or at the header size limits.
func IsGeneratedContent(content string) bool {
	if content == "" {
		return false
	}
	if len(content) > generatedHeaderMaxBytes {
		content = content[:generatedHeaderMaxBytes]
	}
	content = strings.TrimPrefix(content, "\ufeff")

	inBlock := false
	for i, line := range strings.SplitN(content, "\n", generatedHeaderMaxLines+1) {
		if i == generatedHeaderMaxLines {
			break
		}
		found, done := scanHeaderLine(strings.TrimSpace(line), &inBlock)
		if found {
			return true
		}
		if done {
			return false
		}
	}
	return false
}

// scanHeaderLine walks the comments on one header line. found reports a
// marker inside comment text; done reports that the line reached code, which
// ends the header. inBlock carries an open /* */ comment across lines.
func scanHeaderLine(line string, inBlock *bool) (found, done bool) {
	for line != "" {
		if *inBlock {
			end := strings.Index(line, "*/")
			if end < 0 {
				return generatedMarker.MatchString(line), false
			}
			if generatedMarker.MatchString(line[:end]) {
				return true, false
			}
			*inBlock = false
			line = strings.TrimSpace(line[end+2:])
			continue
		}
		switch {
		case strings.HasPrefix(line, "/*"):
			*inBlock = true
			line = line[2:]
		case strings.HasPrefix(line, "<?php"):
			line = strings.TrimSpace(line[len("<?php"):])
		case strings.HasPrefix(line, "//"), strings.HasPrefix(line, "#"),
			strings.HasPrefix(line, "--"), strings.HasPrefix(line, ";"):
			return generatedMarker.MatchString(line), false
		default:
			return false, true
		}
	}
	return false, false
}

// AddsGeneratedMarker reports whether a unified diff adds a generated-code
// marker without removing one. A file that already carried the marker shows
// it as unchanged context, or as a removed and an added line when a generator
// rewrites its header, so only a marker the change itself introduces counts.
// Callers use this to stop a change from hiding an existing hand-written file
// from review by prepending a marker to it.
func AddsGeneratedMarker(diff string) bool {
	added, removed := false, false
	inHunk := false
	for _, line := range strings.Split(diff, "\n") {
		if strings.HasPrefix(line, "@@") {
			inHunk = true
			continue
		}
		if !inHunk || line == "" {
			continue
		}
		switch line[0] {
		case '+':
			added = added || generatedMarker.MatchString(line[1:])
		case '-':
			removed = removed || generatedMarker.MatchString(line[1:])
		}
	}
	return added && !removed
}

func TestIsGeneratedContent(t *testing.T) {
	tests := []struct {
		name    string
		content string
		want    bool
	}{
		{"empty", "", false},
		{"go marker on first line", "// Code generated by mockgen. DO NOT EDIT.\npackage mocks\n", true},
		{"go stringer marker", "// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\n\npackage x\n", true},
		{"go marker after license block", "/*\nCopyright The Kubernetes Authors.\n\nLicensed under the Apache License.\n*/\n\n// Code generated by deepcopy-gen. DO NOT EDIT.\n\npackage v1\n", true},
		{"go marker after build tag", "//go:build !ignore_autogenerated\n\n// Code generated by controller-gen. DO NOT EDIT.\n\npackage v1\n", true},
		{"protoc python", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: a.proto\nimport x\n", true},
		{"grpc python", "# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!\n\"\"\"Client and server classes.\"\"\"\nimport grpc\n", true},
		{"protoc php after open tag", "<?php\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: a.proto\n\nnamespace A;\n", true},
		{"at-generated js block", "/**\n * @generated SignedSource<<abc>>\n */\n'use strict';\n", true},
		{"at-generated rust", "// @generated by prost-build\nuse x;\n", true},
		{"at-generated sql dash comment", "-- @generated\nSELECT 1;\n", true},
		{"dotnet auto-generated", "//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n//------------------------------------------------------------------------------\nnamespace A {}\n", true},
		{"single-line block comment", "/* Code generated by ent, DO NOT EDIT. */\npackage ent\n", true},
		{"utf8 bom", "\ufeff// Code generated by sqlc. DO NOT EDIT.\npackage db\n", true},
		{"crlf line endings", "// Code generated by templ - DO NOT EDIT.\r\n\r\npackage views\r\n", true},

		{"hand-written go", "// Package foo does things.\npackage foo\n", false},
		{"marker after code", "package foo\n\n// Code generated by x. DO NOT EDIT.\n", false},
		{"marker in string literal", "package foo\n\nconst header = \"// Code generated by x. DO NOT EDIT.\"\n", false},
		{"marker in python docstring", "\"\"\"Code generated by x. DO NOT EDIT.\"\"\"\n", false},
		{"generated without do not edit", "// Code generated by hand, review carefully.\npackage foo\n", false},
		{"do not edit without generated", "// DO NOT EDIT this file without asking the owners.\npackage foo\n", false},
		{"lowercase do not edit", "// Generated by x; do not edit the section below by hand.\npackage foo\n", false},
		{"partially generated", "// @partially-generated\npackage foo\n", false},
		{"email-like at-generated", "// Contact: build@generated.example\npackage foo\n", false},
		{"java Generated annotation is code", "package a;\n@Generated(\"x\")\nclass A {}\n", false},
		{"at-generatedfoo is not the token", "// @generatedFoo\npackage foo\n", false},
		{"marker in code after a closed block comment", "/* License */ const label = \"@generated\";\n", false},
		{"code after a closed block comment ends the header", "/* License */ const a = 1;\n// Code generated by x. DO NOT EDIT.\n", false},
		{"code after a multi-line block comment ends the header", "/*\n License\n*/ package foo\n// Code generated by x. DO NOT EDIT.\n", false},
		{"line comment after code", "package foo // Code generated by x. DO NOT EDIT.\n", false},
		{"two block comments on one line", "/* License */ /* Code generated by ent, DO NOT EDIT. */\npackage ent\n", true},
		{"block comment closed before a line comment", "/* License */ // Code generated by x. DO NOT EDIT.\npackage foo\n", true},
		{"php open tag with trailing comment", "<?php // @generated\nnamespace A;\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := IsGeneratedContent(tt.content); got != tt.want {
				t.Errorf("IsGeneratedContent(%q) = %v, want %v", tt.content, got, tt.want)
			}
		})
	}
}

func TestIsGeneratedContent_HeaderLimits(t *testing.T) {
	marker := "// Code generated by x. DO NOT EDIT.\n"

	t.Run("marker past the line limit", func(t *testing.T) {
		content := strings.Repeat("//\n", generatedHeaderMaxLines) + marker
		if IsGeneratedContent(content) {
			t.Fatal("a marker past the header line limit must not count")
		}
	})
	t.Run("marker on the last scanned line", func(t *testing.T) {
		content := strings.Repeat("//\n", generatedHeaderMaxLines-1) + marker
		if !IsGeneratedContent(content) {
			t.Fatal("a marker on the last scanned line must count")
		}
	})
	t.Run("marker past the byte limit", func(t *testing.T) {
		content := "// " + strings.Repeat("x", generatedHeaderMaxBytes) + "\n" + marker
		if IsGeneratedContent(content) {
			t.Fatal("a marker past the header byte limit must not count")
		}
	})
	t.Run("marker inside an unterminated block comment", func(t *testing.T) {
		content := "/*\n License text without leading stars\n Code generated by x. DO NOT EDIT.\n"
		if !IsGeneratedContent(content) {
			t.Fatal("a marker inside a block comment must count")
		}
	})
}

func TestAddsGeneratedMarker(t *testing.T) {
	const header = "diff --git a/auth.go b/auth.go\nindex 1..2 100644\n--- a/auth.go\n+++ b/auth.go\n"
	tests := []struct {
		name string
		diff string
		want bool
	}{
		{"empty", "", false},
		{"marker added to an existing file", header + "@@ -1,3 +1,4 @@\n+// Code generated by example. DO NOT EDIT.\n package auth\n", true},
		{"at-generated added", header + "@@ -1,2 +1,3 @@\n+// @generated\n package auth\n", true},
		{"marker untouched, body changed", header + "@@ -10,3 +10,3 @@\n func f() {\n-\treturn 1\n+\treturn 2\n }\n", false},
		{"marker unchanged in context", header + "@@ -1,3 +1,3 @@\n // Code generated by mockgen. DO NOT EDIT.\n-var V = 1\n+var V = 2\n", false},
		{"marker rewritten by a generator bump", header + "@@ -1,2 +1,2 @@\n-// Code generated by controller-gen v0.15. DO NOT EDIT.\n+// Code generated by controller-gen v0.16. DO NOT EDIT.\n package v1\n", false},
		{"file header lines are not content", "diff --git a/x b/x\n--- a/@generated\n+++ b/@generated\n@@ -1 +1 @@\n-a\n+b\n", false},
		{"added line that looks like a file header", header + "@@ -1,1 +1,2 @@\n+++ @generated\n package auth\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := AddsGeneratedMarker(tt.diff); got != tt.want {
				t.Errorf("AddsGeneratedMarker(%q) = %v, want %v", tt.diff, got, tt.want)
			}
		})
	}
}

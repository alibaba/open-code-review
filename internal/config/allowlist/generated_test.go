func TestIsGeneratedFile(t *testing.T) {
	tests := []struct {
		name    string
		path    string
		content string
		want    bool
	}{
		{"empty", "x.go", "", false},
		{"go marker on first line", "x.go", "// Code generated by mockgen. DO NOT EDIT.\npackage mocks\n", true},
		{"go stringer marker", "x.go", "// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\n\npackage x\n", true},
		{"go marker after license block", "x.go", "/*\nCopyright The Kubernetes Authors.\n\nLicensed under the Apache License.\n*/\n\n// Code generated by deepcopy-gen. DO NOT EDIT.\n\npackage v1\n", true},
		{"go marker after build tag", "x.go", "//go:build !ignore_autogenerated\n\n// Code generated by controller-gen. DO NOT EDIT.\n\npackage v1\n", true},
		{"protoc python", "a_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: a.proto\nimport x\n", true},
		{"grpc python", "a_pb2_grpc.py", "# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!\n\"\"\"Client and server classes.\"\"\"\nimport grpc\n", true},
		{"protoc php after open tag", "A.php", "<?php\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: a.proto\n\nnamespace A;\n", true},
		{"at-generated js block", "relay.js", "/**\n * @generated SignedSource<<abc>>\n */\n'use strict';\n", true},
		{"at-generated rust", "a.rs", "// @generated by prost-build\nuse x;\n", true},
		{"at-generated sql dash comment", "q.sql", "-- @generated\nSELECT 1;\n", true},
		{"dotnet auto-generated", "A.Designer.cs", "//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n//------------------------------------------------------------------------------\nnamespace A {}\n", true},
		{"single-line block comment", "x.go", "/* Code generated by ent, DO NOT EDIT. */\npackage ent\n", true},
		{"utf8 bom", "x.go", "\ufeff// Code generated by sqlc. DO NOT EDIT.\npackage db\n", true},
		{"crlf line endings", "x.go", "// Code generated by templ - DO NOT EDIT.\r\n\r\npackage views\r\n", true},

		{"hand-written go", "x.go", "// Package foo does things.\npackage foo\n", false},
		{"marker after code", "x.go", "package foo\n\n// Code generated by x. DO NOT EDIT.\n", false},
		{"marker in string literal", "x.go", "package foo\n\nconst header = \"// Code generated by x. DO NOT EDIT.\"\n", false},
		{"marker in python docstring", "a.py", "\"\"\"Code generated by x. DO NOT EDIT.\"\"\"\n", false},
		{"generated without do not edit", "x.go", "// Code generated by hand, review carefully.\npackage foo\n", false},
		{"do not edit without generated", "x.go", "// DO NOT EDIT this file without asking the owners.\npackage foo\n", false},
		{"lowercase do not edit", "x.go", "// Generated by x; do not edit the section below by hand.\npackage foo\n", false},
		{"partially generated", "x.go", "// @partially-generated\npackage foo\n", false},
		{"email-like at-generated", "x.go", "// Contact: build@generated.example\npackage foo\n", false},
		{"java Generated annotation is code", "A.java", "package a;\n@Generated(\"x\")\nclass A {}\n", false},
		{"at-generatedfoo is not the token", "x.go", "// @generatedFoo\npackage foo\n", false},
		{"marker in code after a closed block comment", "label.js", "/* License */ const label = \"@generated\";\n", false},
		{"code after a closed block comment ends the header", "a.js", "/* License */ const a = 1;\n// Code generated by x. DO NOT EDIT.\n", false},
		{"code after a multi-line block comment ends the header", "x.go", "/*\n License\n*/ package foo\n// Code generated by x. DO NOT EDIT.\n", false},
		{"line comment after code", "x.go", "package foo // Code generated by x. DO NOT EDIT.\n", false},
		{"two block comments on one line", "x.go", "/* License */ /* Code generated by ent, DO NOT EDIT. */\npackage ent\n", true},
		{"block comment closed before a line comment", "x.go", "/* License */ // Code generated by x. DO NOT EDIT.\npackage foo\n", true},
		{"php open tag with trailing comment", "A.php", "<?php // @generated\nnamespace A;\n", true},
		{"semicolon is code in javascript", "a.js", "; const label = \"@generated\";\n", false},
		{"semicolon comment in clojure", "core.clj", "; @generated\n(ns core)\n", true},
		{"hash is a directive in c", "a.c", "#include <stdio.h>\n// Code generated by x. DO NOT EDIT.\n", false},
		{"hash comment in yaml", "crd.yaml", "# Code generated by controller-gen. DO NOT EDIT.\napiVersion: v1\n", true},
		{"line comment is code in css", "a.css", "// @generated\na { color: red }\n", false},
		{"block comment in css", "a.css", "/* @generated */\na { color: red }\n", true},
		{"dash comment in lua", "a.lua", "-- Code generated by x. DO NOT EDIT.\nlocal a = 1\n", true},
		{"block comment is code in python", "a.py", "/* @generated */\nimport x\n", false},
		{"php tag outside php", "a.go", "<?php // @generated\n", false},
		{"unknown language is never generated", "page.html", "<!-- @generated -->\n<html></html>\n", false},
		{"no extension", "Makefile", "# Code generated by x. DO NOT EDIT.\nall:\n", false},
		{"extension case-insensitive", "A.GO", "// Code generated by x. DO NOT EDIT.\npackage a\n", true},
		{"at-generated in a url", "x.go", "// See https://example.com/@generated\npackage x\n", false},
		{"at-generated right after the comment prefix", "x.go", "//@generated\npackage x\n", true},
		{"cargo-style at-generated in prose", "a.toml", "# This file is automatically @generated by Cargo.\n[package]\n", true},
		{"auto-generated mentioned in prose", "A.cs", "// see <auto-generated> docs\nnamespace A {}\n", false},
		{"auto-generated in a block comment", "A.cs", "/*\n * <auto-generated>\n */\nnamespace A {}\n", true},
		{"auto-generated in a single-line block comment", "A.cs", "/* <auto-generated /> */\nnamespace A {}\n", true},
		{"php attribute is code", "A.php", "<?php\n#[SomeAttribute(\"@generated\")]\nclass A {}\n", false},
		{"php attribute after a comment line", "A.php", "<?php\n# License\n#[Generated(\"Code generated by x. DO NOT EDIT.\")]\nclass A {}\n", false},
		{"hash-bracket is a comment in python", "a.py", "#[x] @generated\nimport x\n", true},
		{"js line separator ends a comment", "a.js", "// license\u2028const label = \"@generated\";\n", false},
		{"js paragraph separator ends a comment", "a.js", "// license\u2029const label = \"@generated\";\n", false},
		{"next line ends a comment", "A.cs", "// license\u0085var label = \"<auto-generated>\";\n", false},
		{"lone carriage return ends a comment", "a.js", "// license\rconst label = \"@generated\";\n", false},
		{"line separator inside a block comment", "a.js", "/* license\u2028 @generated */\nconst a = 1;\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := IsGeneratedFile(tt.path, tt.content); got != tt.want {
				t.Errorf("IsGeneratedFile(%q, %q) = %v, want %v", tt.path, tt.content, got, tt.want)
			}
		})
	}
}

func TestIsGeneratedFile_HeaderLimits(t *testing.T) {
	marker := "// Code generated by x. DO NOT EDIT.\n"

	t.Run("marker past the line limit", func(t *testing.T) {
		content := strings.Repeat("//\n", generatedHeaderMaxLines) + marker
		if IsGeneratedFile("x.go", content) {
			t.Fatal("a marker past the header line limit must not count")
		}
	})
	t.Run("marker on the last scanned line", func(t *testing.T) {
		content := strings.Repeat("//\n", generatedHeaderMaxLines-1) + marker
		if !IsGeneratedFile("x.go", content) {
			t.Fatal("a marker on the last scanned line must count")
		}
	})
	t.Run("marker past the byte limit", func(t *testing.T) {
		content := "// " + strings.Repeat("x", generatedHeaderMaxBytes) + "\n" + marker
		if IsGeneratedFile("x.go", content) {
			t.Fatal("a marker past the header byte limit must not count")
		}
	})
	t.Run("marker inside an unterminated block comment", func(t *testing.T) {
		content := "/*\n License text without leading stars\n Code generated by x. DO NOT EDIT.\n"
		if !IsGeneratedFile("x.go", content) {
			t.Fatal("a marker inside a block comment must count")
		}
	})
}

package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
	"unicode/utf16"

	"github.com/alibaba/open-code-review/internal/llm"
)

const kotlinDeclaration = "internal fun generatedPresetProviderNames(): Set<String> = setOf("

var kotlinPreamble = preambleSyntax{
	declaration:         regexp.MustCompile(`^package[ \t\f]+com\.alibaba\.opencodereview\.idea\.services`),
	whitespace:          regexp.MustCompile(`^[ \t\r\n\f]+`),
	lineTerminators:     "\r\n",
	nestedBlockComments: true,
}

const kotlinHeader = `// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 alibaba/open-code-review Contributors

// Code generated by go generate ./internal/llm; DO NOT EDIT.
// Source: internal/llm/providers.go. Providers are sorted by name.

package com.alibaba.opencodereview.idea.services

`

func renderKotlin(providers []llm.Provider) []byte {
	var out strings.Builder
	out.WriteString(kotlinHeader + kotlinDeclaration + "\n")
	for _, provider := range providers {
		out.WriteString("    " + quoteKotlinString(provider.Name) + ",\n")
	}
	out.WriteString(")\n")
	return []byte(out.String())
}

func quoteKotlinString(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, r := range value {
		switch {
		case r == '"' || r == '\\':
			out.WriteByte('\\')
			out.WriteRune(r)
		case r < 0x20 || r > 0x7e || r == '$':
			// JSON-compatible escapes also prevent Kotlin string interpolation.
			for _, codeUnit := range utf16.Encode([]rune{r}) {
				fmt.Fprintf(&out, "\\u%04x", codeUnit)
			}
		default:
			out.WriteRune(r)
		}
	}
	out.WriteByte('"')
	return out.String()
}

func checkKotlinNames(data []byte, providers []llm.Provider) error {
	preamble, payload, found := bytes.Cut(data, []byte(kotlinDeclaration))
	if !found {
		return fmt.Errorf("missing generatedPresetProviderNames declaration")
	}
	if !kotlinPreamble.matches(preamble) {
		return fmt.Errorf("expected Kotlin package com.alibaba.opencodereview.idea.services before generatedPresetProviderNames")
	}
	payload = bytes.TrimSpace(payload)
	if !bytes.HasSuffix(payload, []byte(")")) {
		return fmt.Errorf("Kotlin provider names must end with a closing parenthesis")
	}
	payload = bytes.TrimSuffix(bytes.TrimSpace(bytes.TrimSuffix(payload, []byte(")"))), []byte(","))
	var names []*string
	if err := json.Unmarshal([]byte("["+string(payload)+"]"), &names); err != nil {
		return fmt.Errorf("decode Kotlin provider names: %w", err)
	}
	if len(names) != len(providers) {
		return fmt.Errorf("Kotlin provider count is %d, want %d", len(names), len(providers))
	}
	for i, provider := range providers {
		if names[i] == nil {
			return fmt.Errorf("Kotlin provider at index %d must be a string", i)
		}
		if *names[i] != provider.Name {
			return fmt.Errorf("Kotlin provider at index %d is %q, want %q", i, *names[i], provider.Name)
		}
	}
	return nil
}
